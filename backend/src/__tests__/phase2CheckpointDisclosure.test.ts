import * as fs from 'fs';
import * as path from 'path';

/**
 * T217 — the checkpoint's behaviour-change list, asserted complete against the
 * enumeration it claims to be derived from.
 *
 * ── WHY THIS EXISTS ────────────────────────────────────────────────────────
 *
 * T217's acceptance says the disclosure list must be "derived from T202's
 * committed enumeration **and asserted complete against it**". I derived it by
 * command and wrote the result into §G — and then shipped the checkpoint without
 * the assertion, so nothing stopped the two drifting apart. I found this by
 * re-reading my own acceptance criteria after the phase was merged, which is the
 * second deliverable in this task I had to discover that way (the handoff was
 * the first).
 *
 * The risk is specific and not hypothetical. `FREE_ACCOUNT_CONSUMERS.md` is
 * GENERATED by a scan, so it grows when somebody adds a consumer. §G is prose
 * someone typed. Without this test, a seventeenth branching consumer appears in
 * the enumeration and the checkpoint keeps claiming sixteen — which is exactly
 * the "a remembered list is always short" failure the plan wrote §G to prevent.
 *
 * ── WHAT IT DOES NOT CHECK ─────────────────────────────────────────────────
 *
 * It compares FILE PATHS, not the prose beside them. A §G entry that names the
 * right file and describes the wrong consequence passes this test. That is a
 * human read, and nothing mechanical here substitutes for it.
 */

const DOCS = path.join(__dirname, '..', '..', '..', 'docs', 'growth-os-reset');
const ENUMERATION = path.join(DOCS, 'FREE_ACCOUNT_CONSUMERS.md');
const CHECKPOINT = path.join(DOCS, 'PHASE_2_CHECKPOINT.md');

/**
 * One file deliberately in §G that the scan does NOT mark CHANGES.
 *
 * `portalSettingsService` returns `tier` and `enrollment_type` straight to the
 * portal, so an Explorer's Settings page reads `explorer` / `guest` where it used
 * to read `standard` / `member`. The enumeration classifies it REPORTING, which
 * is the same misfile class the doc itself already flags in bold for
 * `paymentSyncService`. It is disclosed by judgement rather than by the scan, and
 * it is declared here so "extra entry" cannot become a silent habit.
 */
const DELIBERATE_ADDITIONS = ['services/portalSettingsService.ts'];

/** Every line the enumeration marks as CHANGING behaviour, parsed or not. */
export function changesLines(doc: string): string[] {
  return doc.split('\n').filter((l) => l.startsWith('|') && l.includes('**CHANGES**'));
}

/**
 * Files the enumeration's scan marks as CHANGING behaviour.
 *
 * The path cell is matched with an optional `**` on either side. A verifier beat
 * the first version of this function with a single bolded cell —
 * `| 33 | **\`services/plantedBold.ts\`** | … | **CHANGES** |` — which the regex
 * missed, `.filter(Boolean)` then dropped, and the count check waved through
 * because 16 + 1 still equalled 17 by coincidence. A seventeenth consumer was
 * therefore undisclosed with this suite reporting 8/8 green: the exact scenario
 * the docblock above says it exists to prevent.
 *
 * Rows 29, 30 and 32 of the enumeration were hand-appended, so a hand-formatted
 * row is the realistic path to this, not a contrived one. `parsesEveryRow` below
 * is the assertion that makes a future formatting variant fail loudly instead of
 * silently shrinking the set.
 */
export function changesRows(doc: string): string[] {
  return changesLines(doc)
    .map((l) => {
      const m = l.match(/^\|\s*\d+\s*\|\s*\*{0,2}`([^`]+)`\*{0,2}\s*\|/);
      return m ? m[1] : '';
    })
    .filter(Boolean)
    .sort();
}

/** True when every CHANGES line yielded a path — i.e. the parser saw them all. */
export function parsesEveryRow(doc: string): boolean {
  return changesRows(doc).length === changesLines(doc).length;
}

/** Files §G of the checkpoint discloses, from its numbered list. */
export function disclosedFiles(doc: string): string[] {
  const start = doc.indexOf('## G ·');
  const end = doc.indexOf('## H ·', start);
  if (start < 0 || end < 0) throw new Error('could not locate section G');
  return doc
    .slice(start, end)
    .split('\n')
    .map((l) => l.match(/^\d+\.\s*`([^`]+)`/))
    .filter((m): m is RegExpMatchArray => m !== null)
    .map((m) => m[1])
    .sort();
}

const enumeration = fs.readFileSync(ENUMERATION, 'utf8');
const checkpoint = fs.readFileSync(CHECKPOINT, 'utf8');

describe('T217 — section G is complete against the generated enumeration', () => {
  it('discloses EVERY file the scan marks as changing behaviour', () => {
    // The direction that matters. A consumer the scan finds and the checkpoint
    // omits is an undisclosed behaviour change.
    const missing = changesRows(enumeration)
      .filter((f) => !disclosedFiles(checkpoint).includes(f));
    expect(missing).toEqual([]);
  });

  it('invents nothing: every disclosed file is either in the scan or declared here', () => {
    const allowed = new Set([...changesRows(enumeration), ...DELIBERATE_ADDITIONS]);
    const invented = disclosedFiles(checkpoint).filter((f) => !allowed.has(f));
    expect(invented).toEqual([]);
  });

  it('the counts agree, so a drift of one is caught and not rounded away', () => {
    expect(disclosedFiles(checkpoint)).toHaveLength(
      changesRows(enumeration).length + DELIBERATE_ADDITIONS.length,
    );
  });

  it('every deliberate addition really is absent from the scan', () => {
    // Otherwise the allowance above would quietly cover a file the scan DOES
    // mark, and the second test would stop meaning anything.
    for (const f of DELIBERATE_ADDITIONS) {
      expect(changesRows(enumeration)).not.toContain(f);
    }
  });
});

describe('T217 — the extractors can fail, so the comparisons above mean something', () => {
  it('reads a non-empty set from BOTH documents', () => {
    // Two empty arrays compare equal. Without this, every assertion above would
    // pass if either parser silently matched nothing.
    expect(changesRows(enumeration).length).toBeGreaterThan(10);
    expect(disclosedFiles(checkpoint).length).toBeGreaterThan(10);
  });

  it('PARSES EVERY CHANGES ROW — a row it cannot read is not a row it may skip', () => {
    // The hole a verifier drove a planted consumer through. Dropping an
    // unparseable row shrinks the set being compared, so the comparison passes
    // while the thing it is comparing has grown.
    expect(changesRows(enumeration)).toHaveLength(changesLines(enumeration).length);
    expect(parsesEveryRow(enumeration)).toBe(true);
  });

  it('CATCHES a BOLDED path cell, which is how it was beaten', () => {
    // The verifier's exact mutation. It must now either parse (and be compared)
    // or fail the completeness check — never be silently dropped.
    const planted = `${enumeration}\n| 33 | **\`services/plantedBold.ts\`** | x | **CHANGES** | — | planted |`;
    expect(parsesEveryRow(planted)).toBe(true);
    expect(changesRows(planted)).toContain('services/plantedBold.ts');
    const missing = changesRows(planted)
      .filter((f) => !disclosedFiles(checkpoint).includes(f));
    expect(missing).toEqual(['services/plantedBold.ts']);
  });

  it('FAILS LOUDLY on a row shape it genuinely cannot parse', () => {
    // The other half: if a future row defeats the regex entirely, the
    // completeness assertion must go false rather than the row vanishing.
    const unparseable = `${enumeration}\n| 34 | services/noBackticks.ts | x | **CHANGES** | — | planted |`;
    expect(parsesEveryRow(unparseable)).toBe(false);
  });

  it('CATCHES a planted enumeration row the checkpoint does not disclose', () => {
    // The positive control, and the real failure mode: a new consumer appears in
    // the generated scan and §G keeps its old list.
    const planted = `${enumeration}\n| 99 | \`services/plantedConsumer.ts\` | x | **CHANGES** | — | planted |`;
    const missing = changesRows(planted)
      .filter((f) => !disclosedFiles(checkpoint).includes(f));
    expect(missing).toEqual(['services/plantedConsumer.ts']);
  });

  it('CATCHES a checkpoint entry with no row behind it', () => {
    // The other direction: prose that names a file the scan never found.
    const planted = checkpoint.replace(
      '## H ·',
      '17. `services/inventedByProse.ts` — not in any scan.\n\n## H ·',
    );
    const allowed = new Set([...changesRows(enumeration), ...DELIBERATE_ADDITIONS]);
    const invented = disclosedFiles(planted).filter((f) => !allowed.has(f));
    expect(invented).toEqual(['services/inventedByProse.ts']);
  });

  it('does NOT treat a REPORTING row as a behaviour change', () => {
    // The enumeration has two outcome columns. Only CHANGES belongs in §G, and
    // mistaking one for the other is how the list would inflate instead of
    // going short.
    const reportingOnly = '| 98 | `services/reportingOnly.ts` | x | — | — | reporting |';
    expect(changesRows(reportingOnly)).toEqual([]);
  });
});
