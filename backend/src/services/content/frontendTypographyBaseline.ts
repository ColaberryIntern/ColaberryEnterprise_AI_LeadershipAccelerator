import { DASH_RULE, EMOJI_RULE, ESCAPED_DASH_RULE, FRONTEND_TYPOGRAPHY_RULES } from './bannedCopyRule';
import { BASELINE_SCOPE, isInScope } from './frontendCopyBaseline';
import rawBaseline from './frontendTypographyBaseline.json';

/**
 * frontendTypographyBaseline - the frozen, SHRINK-ONLY high-water mark for em dashes, en
 * dashes and emoji in frontend copy.
 *
 * The sibling of `frontendCopyBaseline.ts`, deliberately built to the same shape and for the
 * same reason: the rule was already being broken 2,840 times when it was written, so a lint
 * that simply fails could not be merged. It would block every unrelated pull request until a
 * 700-file copy rewrite landed, so it would be switched off instead, and a switched-off lint
 * is worth less than no lint because of the tick it earned on the way past.
 *
 * ## Why the numbers live in a JSON file next door
 *
 * 795 entries is 800 lines of data. Holding it in a TypeScript module would put that module
 * well past this repo's 500-line hard ceiling while adding nothing a reader could act on, so
 * the DATA is data and this module is the part with reasoning in it. The JSON is generated by
 * the measurement; everything below is hand-written and is what a reviewer should read.
 *
 * ## What a number counts
 *
 * Occurrences, not lines, classified by `bannedCopyScanner` exactly as the word lint is. A
 * dash or an emoji inside a comment, an import path, an object key or a machinery attribute
 * is excluded there and is not counted here - which matters more for this rule than for the
 * word one, because 3,476 of the 5,585 dashes in scope are in JSDoc. A gate that counted
 * those would be reporting on this repo's documentation style, not on its product copy.
 *
 * ## MEASURED 2026-11-13, against `main` at c4d3bf17c
 *
 *   1,659 files in scope, parsed once each, 2.2 seconds.
 *
 *   em/en dash     5,585 raw = 2,107 copy + 3,476 comment + 2 regex-literal   (580 files)
 *   escaped dash      74 raw =    74 copy                                     ( 42 files)
 *   emoji            764 raw =   659 copy +   103 comment + 1 regex-literal   (173 files)
 *
 *   Nothing unclassified, and the parser's count equalled the raw count for every file under
 *   all three rules. That second number is the one that makes the first believable: an
 *   occurrence the scanner could not place is reported as a FAILURE, never skipped.
 *
 *   READ THE ESCAPED-DASH ROW AGAIN: 74 raw, 74 copy, NOTHING in a comment. Every single
 *   `&mdash;` in this tree is in something a person reads. That row is also the reason the
 *   rule exists - `DASH_RULE` caught none of them, because the source text holds seven ASCII
 *   characters and not U+2014, so the dash gate shipped at 97% of the truth until this was
 *   measured. See `ESCAPED_DASH_RULE` for the completeness argument and for the one hole that
 *   remains named rather than closed (emoji written as a numeric character reference).
 *
 * ## How to change it
 *
 * Fix the copy, run the suite, and paste the number the failure tells you. Never raise an
 * entry to make a build pass - raising one is the thing this file exists to prevent. For a
 * dash, write a comma, a full stop, a colon or the word "to", choosing by what the dash was
 * doing; there is no mechanical substitution, which is why the rule reports and never
 * repairs. For an emoji, use an icon component or nothing.
 *
 * ## The scope is borrowed, not redeclared
 *
 * `BASELINE_SCOPE` and `isInScope` come from `frontendCopyBaseline.ts` and are re-exported
 * here rather than copied. Two baselines with two scope definitions would eventually disagree
 * about which files are covered, and the file that fell through the gap would be the one
 * nobody was counting. There is one answer to "is this file in scope" in this subsystem.
 */

export { BASELINE_SCOPE, isInScope };

/** Repo-relative paths with forward slashes, mapped to the exact number of copy occurrences. */
export type TypographyBaseline = Readonly<Record<string, number>>;

/**
 * Keyed by rule id, so a count is attributed to the rule that produced it.
 *
 * The cast is the one place the JSON's wide type is narrowed. It is safe in the direction
 * that matters: `assertBaselineIntegrity` below checks at module load that every key is a
 * known rule id and every value is a positive integer, so a hand-edit that breaks the shape
 * fails loudly instead of being read as a file with no violations.
 */
export const FRONTEND_TYPOGRAPHY_BASELINE: Readonly<Record<string, TypographyBaseline>> =
  rawBaseline as Readonly<Record<string, TypographyBaseline>>;

/**
 * The sums the baseline asserts, kept beside it so a careless edit to the table is visible.
 *
 * All three were first measured on 2026-11-13. When one changes, say here which direction and
 * why, as `frontendCopyBaseline.ts` does - the history of that file's total is the clearest
 * record in this subsystem of the ratchet actually turning.
 *
 * **emoji: 660 at first measurement, 659 in the same change.** The portal's own watch button
 * read "[play triangle] Watch here", which DOC 18 named as a violation, and the triangle was
 * decoration in front of a label that already said what the button does - so removing it loses
 * nothing a person was reading. `LiveWorkspace.tsx` passed the same glyph again as `&#9654;`,
 * which is how the escaped hole was found in the first place. Both are gone and
 * `BroadcastWatchButton.tsx` is clean, so its entry is DELETED rather than set to zero.
 *
 * **em/en dash: 2107 -> 2101 (Services Upgrade SV3, 2026-11-13).** The Our Services rebuild
 * replaced `AdminGovServicesPage.tsx` with a composer that has no dashes (its six were dash
 * placeholders and form hints), so its entry is DELETED. The new SV3 components carry none:
 * empty values read "None" or "n/a". Emoji stayed at 659: the mockup's emoji were rendered as
 * RemixIcon icons rather than added to the baseline.
 *
 * And the same caveat applies, because it is the one that is easy to get wrong: the invariant
 * is "may only go down AT A FIXED SCOPE", not "may only go down". `BASELINE_SCOPE` is shared
 * with the word lint, so widening it there re-bases these totals too. A re-base is not a
 * regression; it is the measurement catching up with the tree, and conflating the two is how a
 * lint quietly keeps reporting a number better than the truth.
 */
export const FRONTEND_TYPOGRAPHY_BASELINE_TOTALS: Readonly<Record<string, number>> = {
  [DASH_RULE.id]: 2101,
  [ESCAPED_DASH_RULE.id]: 74,
  [EMOJI_RULE.id]: 659,
};

/**
 * Checked when this module loads, not in a test.
 *
 * A baseline is only worth what its shape is worth. A typo that turned a rule id into one the
 * lint never asks about would take that rule's entire table out of the comparison, and the
 * suite would go green over copy nobody read - the failure mode this subsystem keeps writing
 * headers about. Here it throws on import instead, which fails every suite that touches it.
 */
function assertBaselineIntegrity(): void {
  const known = new Set(FRONTEND_TYPOGRAPHY_RULES.map((r) => r.id));
  for (const [ruleId, files] of Object.entries(FRONTEND_TYPOGRAPHY_BASELINE)) {
    if (!known.has(ruleId)) {
      throw new Error(
        `frontendTypographyBaseline.json names rule "${ruleId}", which is not in `
        + `FRONTEND_TYPOGRAPHY_RULES (${[...known].join(', ')}). A baseline keyed on an unknown `
        + 'rule is never compared against anything.',
      );
    }
    for (const [file, count] of Object.entries(files)) {
      if (!Number.isInteger(count) || count < 1) {
        throw new Error(`frontendTypographyBaseline.json: ${ruleId} / ${file} = ${count}. An entry must be a positive integer; an entry that reaches zero is DELETED, not set to 0.`);
      }
      if (!isInScope(file)) {
        throw new Error(`frontendTypographyBaseline.json: ${ruleId} / ${file} is outside BASELINE_SCOPE, so the lint will never visit it and the entry can never be satisfied.`);
      }
    }
  }
  for (const rule of FRONTEND_TYPOGRAPHY_RULES) {
    if (!(rule.id in FRONTEND_TYPOGRAPHY_BASELINE)) {
      throw new Error(`FRONTEND_TYPOGRAPHY_RULES contains "${rule.id}" with no baseline. Add an entry (an empty object means "this rule is clean everywhere"), so that an absent baseline can never read as a clean tree.`);
    }
  }
}

assertBaselineIntegrity();

/** The recorded count for one file under one rule. Zero means "expected clean". */
export function baselineFor(ruleId: string, file: string): number {
  return FRONTEND_TYPOGRAPHY_BASELINE[ruleId]?.[file] ?? 0;
}
