/**
 * L10.2, the spec: the done-when taken apart clause by clause, each with its own evidence.
 *
 * WHY CLAUSE BY CLAUSE. L10.2's done-when is one sentence with four conditions in it, and a
 * summary that says "met" invites the reader to trust the author's parse of that sentence. Three
 * of the four are arithmetic over the stored document. The fourth - "a human approver that an
 * agent does not fill" - is the one that needed a judgment, because an agent DOES work under the
 * approver role on this decomposition. That clause gets its own section and its own evidence
 * rather than being folded into a tick.
 *
 * Multi-page by design; the one-pager is the other audience.
 */
const D = require('./l10Data');
const { TOKENS, esc, baseCss } = require('../artifactTheme');
const { htmlDoc } = require('../renderArtifactPdf');

/** The four conditions, each with the measurement that settles it. */
const CLAUSES = [
  {
    clause: 'humanAiStructure reports no blocking finding on a real decomposition',
    verdict: 'met',
    evidence: () => `The gate returned <code>passes=true</code>, <code>structured=true</code> and `
      + `${D.TOTALS.blocking + D.TOTALS.warnings} findings, of which `
      + `<strong>${D.TOTALS.blocking} are blocking</strong>. "A real decomposition" is load-bearing: `
      + `this is Herriman's stored v1, generated by the model and persisted, not a fixture.`,
  },
  {
    clause: 'every AI task belongs to exactly one team',
    verdict: 'met',
    evidence: () => `Allocation reports <strong>${D.COUNTS.ai}</strong> tasks of class `
      + `<code>ai_with_approval</code>. The ${D.TOTALS.teams} teams claim `
      + `${D.TEAMS.map((t) => t.taskCount).join(' + ')} = <strong>${D.TOTALS.aiTasksInTeams}</strong> `
      + `tasks between them. Equal counts with no task in two teams is the "exactly one" claim; `
      + `<code>TASK_ONE_TEAM</code> is the rule that would have caught a double-claim and it is silent.`,
  },
  {
    clause: 'no two teams share a subject',
    verdict: 'met',
    evidence: () => `${D.TOTALS.teams} teams, <strong>${D.TOTALS.subjects} distinct subjects</strong>: `
      + `${D.TEAMS.map((t) => `"${esc(t.subject)}"`).join(' and ')}. `
      + `<code>SUBJECT_UNIQUE</code> is the rule; it is silent.`,
  },
  {
    clause: 'every team names a human approver that an agent does not fill',
    verdict: 'met, with the warning below',
    evidence: () => `Both teams name <code>${esc(D.APPROVER_EVIDENCE.roleId)}</code>. Across `
      + `${D.COUNTS.assignments} assignment rows, an agent is PERFORMER on `
      + `${D.APPROVER_EVIDENCE.agentPerformerTasks} tasks under that role and a person is APPROVER `
      + `on ${D.APPROVER_EVIDENCE.personApproverTasks}. `
      + `<strong>${D.APPROVER_EVIDENCE.agentsHoldingApproval} agents hold APPROVER or ACCOUNTABLE.</strong> `
      + `The approval is a person's, so the clause holds. What does not hold is role hygiene, and `
      + `that is reported by name rather than waved through.`,
  },
];

function build() {
  const clauses = CLAUSES.map((c, i) => `<section>
      <h2>Condition ${i + 1} &mdash; <span class="v">${esc(c.verdict)}</span></h2>
      <p class="cl">&ldquo;${esc(c.clause)}&rdquo;</p>
      <p class="ev">${c.evidence()}</p>
    </section>`).join('\n');

  const findings = D.FINDINGS.map((f) => `<tr>
      <td><code>${esc(f.rule)}</code></td>
      <td class="c">${f.count}</td>
      <td class="c sev-${esc(f.severity)}">${esc(f.severity)}</td>
      <td>${esc(f.detail)}</td>
    </tr>`).join('\n');

  const rules = D.GATE.ruleCodes.map((r) => `<li><code>${esc(r)}</code></li>`).join('');
  const controls = D.CONTROLS.map((c) => `<tr><td>${esc(c.claim)}</td>
      <td class="mono">${esc(c.evidence)}</td></tr>`).join('\n');
  const notClaimed = D.NOT_CLAIMED.map((n) => `<li>${esc(n)}</li>`).join('\n');

  const body = `
<h1>L10.2 &mdash; agent teams: one agent, one subject, a person approving</h1>
<p class="sub"><strong>Asked:</strong> emit named, subject-bounded agent teams with a human
approver, an execution policy, an autonomy stage and the INPACT dimensions each must address.
<strong>Delivered:</strong> the structure exists on a real decomposition and the gate passes it
with zero blocking findings &mdash; and two warnings that are real and are named here.</p>
<p class="meta">${esc(D.META.project)} &middot; <code>${esc(D.META.deliveryProjectId)}</code>
&middot; ${esc(D.META.track)} v${D.META.version} (${esc(D.META.status)}), stored
${esc(D.META.docUpdated)} &middot; measured ${esc(D.META.built)} by ${esc(D.META.measuredBy)}
&middot; backend <code>${esc(D.META.deployedSha)}</code>, container up
${esc(D.META.containerStarted)}</p>

<div class="takeaway">
  <strong>TAKEAWAY.</strong> ${D.COUNTS.ai} AI tasks, ${D.TOTALS.teams} named teams,
  ${D.TOTALS.subjects} distinct subjects, ${D.TOTALS.blocking} blocking findings. The generic blob
  this ticket existed to prevent did not happen. The approval is held by a person on every team.
  The two warnings are that no team has been placed on the autonomy ladder, and that the approver
  role is shared with an agent performer &mdash; neither of which is a system approving its own
  work, and both of which are worth fixing.
</div>

<h2 class="big">The done-when, one condition at a time</h2>
<p class="sub">The ticket's criterion is a single sentence containing four conditions. A verdict of
&ldquo;met&rdquo; on the sentence asks the reader to trust a parse, so here is each one separately.</p>
${clauses}

<h2 class="big">What the gate actually said</h2>
<table>
  <thead><tr><th>Rule</th><th class="c">Count</th><th class="c">Severity</th><th>What it means</th></tr></thead>
  <tbody>${findings}</tbody>
</table>
<p class="sub">Severity is the gate's own, not a reading of it. <code>factoryValidate</code>
downgrades every structure finding to a warning for the caller, which is why
<code>blockingFindings</code> is read separately rather than inferred from whether generation
succeeded.</p>

<h2 class="big">The warning that took a correction to state correctly</h2>
<p class="ev">On the first reading of this document the gate reported
<code>APPROVER_IS_AGENT</code> twice &mdash; &ldquo;an agent fills that role. A system may never
be the approver.&rdquo; That was one step from being promoted to a blocking rule on the grounds
that an agent approving an agent defeats the purpose of the ladder.</p>
<p class="ev">It was checked first. Every <em>role</em> in the document carries
<code>executor_type=undefined</code>, so the rule cannot be reading roles at all &mdash; it builds
its set from <strong>assignments</strong>, and those say a person holds the approval. The finding
was <strong>true by its own definition and materially false</strong>. Promoting it would have
rejected a sound decomposition over a naming collision.</p>
<p class="ev">The rule is now two: <code>APPROVER_IS_AGENT</code> stays blocking and fires only
when an agent holds APPROVER or ACCOUNTABLE; <code>APPROVER_ROLE_SHARED_WITH_AGENT</code> is a
warning for the case actually present here. The decomposition prompt now asks for a separate
approver role, so the prompt prevents what the gate reports.</p>

<h2 class="big">The gate's ${D.TOTALS.rules} rules</h2>
<ul class="rules">${rules}</ul>
<p class="sub">${D.GATE.tests} tests in <code>${esc(D.GATE.testFile)}</code>.</p>

<h2 class="big">Shown to catch, not merely shown to pass</h2>
<table>
  <thead><tr><th>Claim</th><th>Where it is proven</th></tr></thead>
  <tbody>${controls}</tbody>
</table>

<h2 class="big">Not claimed</h2>
<ul class="nc">${notClaimed}</ul>
`;

  return htmlDoc({
    title: 'L10.2 — agent teams (spec)',
    css: `${baseCss()}
      .sub { color: ${TOKENS.MUTED}; font-size: 10px; line-height: 1.5; }
      .meta { color: ${TOKENS.MUTED}; font-size: 9px; line-height: 1.5; margin-top: -4px; }
      .takeaway { border: 1px solid ${TOKENS.CHERRY}; background: ${TOKENS.CHERRY_BG};
        border-radius: 6px; padding: 10px 13px; font-size: 10.5px; line-height: 1.55;
        margin: 13px 0 16px; }
      h2.big { font-size: 13px; margin: 20px 0 6px; border-bottom: 1px solid ${TOKENS.BORDER};
        padding-bottom: 4px; }
      section { margin: 10px 0 12px; }
      section h2 { font-size: 11px; margin: 0 0 3px; }
      .v { color: ${TOKENS.SEV.ok}; font-weight: 700; }
      .cl { font-size: 10px; font-style: italic; color: ${TOKENS.INK}; margin: 0 0 4px; }
      .ev { font-size: 10px; line-height: 1.5; border-left: 3px solid ${TOKENS.BORDER};
        padding-left: 10px; margin: 4px 0; }
      table { width: 100%; border-collapse: collapse; font-size: 9.5px; margin: 5px 0; }
      th { text-align: left; background: ${TOKENS.BG_ALT}; padding: 5px 7px;
        border-bottom: 1px solid ${TOKENS.BORDER}; font-size: 9px; color: ${TOKENS.MUTED}; }
      td { padding: 5px 7px; border-bottom: 1px solid ${TOKENS.BORDER}; vertical-align: top;
        line-height: 1.45; }
      td.c { text-align: center; }
      td.mono, .mono { font-family: ui-monospace, monospace; font-size: 8.5px;
        color: ${TOKENS.MUTED}; }
      .sev-warning { color: ${TOKENS.SEV.watch}; font-weight: 700; }
      .sev-blocking { color: ${TOKENS.SEV.bad}; font-weight: 700; }
      ul.rules { columns: 3; font-size: 9px; margin: 4px 0; padding-left: 15px;
        font-family: ui-monospace, monospace; line-height: 1.6; }
      ul.nc { font-size: 10px; line-height: 1.5; padding-left: 16px; }`,
    body,
  });
}

module.exports = { build, CLAUSES };
