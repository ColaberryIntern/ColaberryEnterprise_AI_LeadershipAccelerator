#!/usr/bin/env node
/**
 * Dismiss a whole GENERATION RUN from Ali's queue. DRY RUN BY DEFAULT.
 *
 *   node scripts/ataDismissRun.js --created 2026-06-25,2026-06-24 --reason "demo scaffolding"
 *   ... --apply   to carry it out
 *
 * WHY A RUN AND NOT A LIST
 *
 * Scaffolding is created in bulk, so it clusters by creation day: the 25 Jun run alone is 1,860
 * tasks across 280 lists. Deciding that per list would be 280 decisions of the same decision.
 * Project is the wrong axis too - 2,402 of 2,693 tasks sit in one Basecamp project, so "per
 * project" is one decision covering almost everything.
 *
 * WHAT THIS DOES NOT DO
 *
 * It writes `is_dismissed` on the local mirror. The tickets stay OPEN in Basecamp, the projects
 * still own them, and anyone else assigned still sees them. This removes them from Ali's queue and
 * from every digest built on that mirror. It is not a closure and must never be described as one.
 *
 * THE GUARD THAT MATTERS
 *
 * The 7 Jul run is machine-generated by the same tooling and is NOT scaffolding - it is the
 * R1-R4 gov-contracting ladder with Ali's own approval gates in it. Every marker says "generated";
 * only the creation date tells them apart. So this script asserts, before writing, that the
 * protected lists are absent from the affected set, and aborts if any appear. A date filter is
 * easy to get subtly wrong and the cost of getting it wrong is losing real strategy.
 */
const fs = require('fs');
const { sequelize } = require('/app/dist/config/database');
const { QueryTypes } = require('/app/node_modules/sequelize');

const arg = (k, d = null) => {
  const i = process.argv.indexOf(`--${k}`);
  return i >= 0 && process.argv[i + 1] && !process.argv[i + 1].startsWith('--') ? process.argv[i + 1] : d;
};
const has = (k) => process.argv.includes(`--${k}`);

const DATES = String(arg('created', '')).split(',').map((s) => s.trim()).filter(Boolean);
const REASON = String(arg('reason', '')).trim();
const APPLY = has('apply');
const ALI = 17454835;

/** Anything matching these must never be dismissed by this script. */
const PROTECTED = ['R1 -%', 'R2 -%', 'R3 -%', 'R4 -%', 'MILESTONE APPROVALS%', 'HIGH-LEVEL APPROVALS%'];

if (!DATES.length) { console.error('--created YYYY-MM-DD[,YYYY-MM-DD] is required'); process.exit(1); }
if (!REASON) { console.error('--reason is required: a dismissal nobody can explain later is a deletion'); process.exit(1); }
/**
 * dismissed_reason is VARCHAR(40) - a short code, not prose. Found by a failed apply, which is
 * the good kind of failure: it threw before it wrote. The full rationale goes in the reversal
 * file, which has room for it; this column gets something a person can scan in a query result.
 */
const REASON_MAX = 40;
if (REASON.length > REASON_MAX) {
  console.error(`--reason is ${REASON.length} chars; dismissed_reason holds ${REASON_MAX}.`);
  console.error('Use a short code here and put the full rationale in --note.');
  process.exit(1);
}

const GEN = `((description LIKE '%Type:%' AND description LIKE '%Done when:%')
  OR title LIKE '[BUILD]%' OR title LIKE '[BREAK]%' OR title LIKE '[HARDEN]%'
  OR title LIKE '%\u{1F916}%' OR title LIKE '%\u{1F9D1}%')`;

(async () => {
  const dateList = DATES.map((d) => `'${d}'`).join(',');
  const WHERE = `status = 'active' AND is_dismissed IS NOT TRUE
    AND assignee_ids::text LIKE '%${ALI}%'
    AND bc_created_at::date IN (${dateList})
    AND ${GEN}`;

  const rows = await sequelize.query(
    `SELECT bc_id, project_id, title, todolist_name, due_on, bc_created_at::date AS created
       FROM ops_bc_todos WHERE ${WHERE} ORDER BY bc_created_at, bc_id`,
    { type: QueryTypes.SELECT },
  );

  console.log(`Generation run(s) ${DATES.join(', ')}`);
  console.log(`  ${rows.length} task(s) match: active, assigned to Ali, generated, created on those days.`);

  const byDay = {};
  rows.forEach((r) => { byDay[r.created] = (byDay[r.created] || 0) + 1; });
  Object.entries(byDay).forEach(([d, n]) => console.log(`    ${d}: ${n}`));

  // ---- the guard ----
  const hits = rows.filter((r) => PROTECTED.some((p) => {
    const re = new RegExp('^' + p.replace(/%/g, '.*').replace(/ /g, '\\s'), 'i');
    return re.test(String(r.todolist_name || ''));
  }));
  if (hits.length) {
    console.error('');
    console.error(`ABORTED: ${hits.length} protected task(s) are inside this selection.`);
    hits.slice(0, 5).forEach((h) => console.error(`  ${h.bc_id}  ${h.todolist_name}  ${h.title}`));
    console.error('The gov-contracting ladder must not be dismissed by a run-level sweep.');
    await sequelize.close();
    process.exit(1);
  }
  console.log(`  GUARD PASSED: no protected list (${PROTECTED.join(', ')}) is in this selection.`);

  console.log('');
  console.log('  Sample of what would go:');
  rows.slice(0, 8).forEach((r) => console.log(
    `    ${String(r.bc_id).padEnd(12)} [${String(r.todolist_name).slice(0, 34).padEnd(34)}] ${String(r.title).slice(0, 44)}`));

  console.log('');
  console.log('  These tickets stay OPEN in Basecamp. This removes them from Ali\'s queue only.');

  if (!APPLY) {
    console.log('');
    console.log('DRY RUN. Nothing changed. Add --apply to carry this out.');
    await sequelize.close();
    process.exit(0);
  }

  // The reversal file is written BEFORE the update, so an interrupted run is still undoable.
  // bc_id is VARCHAR in this table, not an integer. The first apply threw on ::bigint and changed
  // nothing, which is the one good thing about a cast error: it fails before it writes.
  const ids = rows.map((r) => String(r.bc_id));
  const revPath = `/tmp/ata-dismiss-reversal-${Date.now()}.json`;
  fs.writeFileSync(revPath, JSON.stringify({
    dismissedAt: new Date().toISOString(), reason: REASON, note: arg('note', ''), created: DATES, bc_ids: ids,
    undo: 'UPDATE ops_bc_todos SET is_dismissed = false, dismissed_at = NULL, dismissed_by = NULL, '
      + 'dismissed_reason = NULL WHERE bc_id = ANY($1::text[])',
  }, null, 2), 'utf8');
  console.log(`  Reversal written first: ${revPath}`);

  const [, affected] = await sequelize.query(
    `UPDATE ops_bc_todos
        SET is_dismissed = true, dismissed_at = now(), dismissed_by = $1, dismissed_reason = $2
      WHERE bc_id = ANY($3::text[]) AND is_dismissed IS NOT TRUE`,
    { type: QueryTypes.UPDATE, bind: ['ata-dismiss-run', REASON, ids.map(String)] },
  );

  console.log('');
  console.log(`APPLIED. ${affected} task(s) removed from the queue.`);
  console.log(`Undo with the ids in ${revPath}.`);

  await sequelize.close();
  process.exit(0);
})().catch((e) => { console.error('FATAL', e && e.message); process.exit(1); });
